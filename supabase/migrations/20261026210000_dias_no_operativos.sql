-- Dias sin ruta. Una fecha, una fila. Solo domingo y festivo nacional (2026 a 2028).
-- Un dia de zona, vacaciones o sembrina no entra aqui: la hoja abre y cierra como cualquier dia.

create table if not exists public.dias_no_operativos (
  fecha date primary key,
  tipo text not null,
  nombre text not null,
  origen text not null,
  nota text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dias_no_operativos_tipo_chk check (tipo in ('domingo', 'festivo')),
  constraint dias_no_operativos_origen_chk check (origen = 'calendario')
);

comment on table public.dias_no_operativos is
  'Dias en los que no nace la ruta: domingo y festivo nacional. Nada mas.';

revoke all on table public.dias_no_operativos from public, anon, authenticated;
grant select, insert, update, delete on table public.dias_no_operativos to service_role;
alter table public.dias_no_operativos enable row level security;

